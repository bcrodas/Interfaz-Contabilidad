SELECT
    SEQUENCE_NAME,
    MIN_VALUE,
    INCREMENT_BY,
    LAST_NUMBER
FROM USER_SEQUENCES
ORDER BY SEQUENCE_NAME;

SELECT
    TRIGGER_NAME,
    TABLE_NAME,
    STATUS,
    TRIGGERING_EVENT
FROM USER_TRIGGERS
WHERE TABLE_NAME IN (
    'TIPOCUENTA',
    'CUENTA',
    'CABECERACOMPROBANTE',
    'DETALLECOMPROBANTE'
)
ORDER BY TABLE_NAME;