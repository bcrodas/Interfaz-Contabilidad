-- Run as CONTABILIDAD with SQL Developer's Run Script (F5), while all
-- applications writing to these tables are stopped. Oracle commits DDL
-- automatically; a failure can leave a partially applied migration.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON

DECLARE
  missing_tables NUMBER;
  conflicting_objects NUMBER;
  conflicting_columns NUMBER;
  conflicting_constraints NUMBER;
  duplicate_account_codes NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'CONTABILIDAD'
     OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'CONTABILIDAD' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Conectese al esquema CONTABILIDAD antes de ejecutar el script.');
  END IF;

  SELECT COUNT(*)
    INTO missing_tables
    FROM (
      SELECT 'TIPOCUENTA' name FROM dual UNION ALL
      SELECT 'CUENTA' FROM dual UNION ALL
      SELECT 'CABECERACOMPROBANTE' FROM dual UNION ALL
      SELECT 'DETALLECOMPROBANTE' FROM dual
    ) expected
   WHERE NOT EXISTS (SELECT 1 FROM user_tables t WHERE t.table_name = expected.name);

  IF missing_tables > 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Faltan tablas de contabilidad en el esquema actual.');
  END IF;

  SELECT COUNT(*)
    INTO conflicting_objects
    FROM user_objects
   WHERE object_name IN (
     'SEQ_TIPOCUENTA', 'SEQ_CUENTA', 'SEQ_CABECERACOMPROBANTE',
     'SEQ_DETALLECOMPROBANTE', 'SEQ_USUARIO_APLICACION',
     'USUARIO_APLICACION'
   );
  IF conflicting_objects > 0 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Ya existe un objeto de esta migracion; revise el esquema antes de continuar.');
  END IF;

  SELECT COUNT(*)
    INTO conflicting_columns
    FROM user_tab_columns
   WHERE table_name = 'TIPOCUENTA'
     AND column_name IN ('NATURALEZA', 'CLASIFICACION');
  IF conflicting_columns > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Ya existen columnas de esta migracion; revise el esquema antes de continuar.');
  END IF;

  SELECT COUNT(*)
    INTO conflicting_constraints
    FROM user_constraints
   WHERE constraint_name IN (
     'CK_TIPOCUENTA_NATURALEZA', 'CK_TIPOCUENTA_CLASIFICACION',
     'UQ_CUENTA_CODIGO', 'UQ_USUARIO_APLICACION_NOMBRE', 'CK_USUARIO_APLICACION_ROL',
     'CK_USUARIO_APLICACION_ACTIVO'
   );
  IF conflicting_constraints > 0 THEN
    RAISE_APPLICATION_ERROR(-20005, 'Ya existen restricciones de esta migracion; revise el esquema antes de continuar.');
  END IF;

  SELECT COUNT(*)
    INTO duplicate_account_codes
    FROM (
      SELECT CODIGO
        FROM CUENTA
       GROUP BY CODIGO
      HAVING COUNT(*) > 1
    );
  IF duplicate_account_codes > 0 THEN
    RAISE_APPLICATION_ERROR(-20006, 'Hay codigos de cuenta duplicados; resuelvalos antes de agregar la restriccion de unicidad.');
  END IF;
END;
/

DECLARE
  next_id NUMBER;
BEGIN
  SELECT GREATEST(NVL(CEIL(MAX(ID_TIPO)), 0) + 1, 1) INTO next_id FROM TIPOCUENTA;
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_TIPOCUENTA START WITH ' || TO_CHAR(next_id, 'FM9999999999999999999999999999') || ' INCREMENT BY 1 NOCYCLE';
  SELECT GREATEST(NVL(CEIL(MAX(ID_CUENTA)), 0) + 1, 1) INTO next_id FROM CUENTA;
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_CUENTA START WITH ' || TO_CHAR(next_id, 'FM9999999999999999999999999999') || ' INCREMENT BY 1 NOCYCLE';
  SELECT GREATEST(NVL(CEIL(MAX(ID_COMPROBANTE)), 0) + 1, 1) INTO next_id FROM CABECERACOMPROBANTE;
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_CABECERACOMPROBANTE START WITH ' || TO_CHAR(next_id, 'FM9999999999999999999999999999') || ' INCREMENT BY 1 NOCYCLE';
  SELECT GREATEST(NVL(CEIL(MAX(ID_DETALLE)), 0) + 1, 1) INTO next_id FROM DETALLECOMPROBANTE;
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_DETALLECOMPROBANTE START WITH ' || TO_CHAR(next_id, 'FM9999999999999999999999999999') || ' INCREMENT BY 1 NOCYCLE';
END;
/

ALTER TABLE TIPOCUENTA ADD (
  NATURALEZA VARCHAR2(10 CHAR),
  CLASIFICACION VARCHAR2(10 CHAR),
  CONSTRAINT CK_TIPOCUENTA_NATURALEZA CHECK (NATURALEZA IN ('DEUDORA', 'ACREEDORA')),
  CONSTRAINT CK_TIPOCUENTA_CLASIFICACION CHECK (CLASIFICACION IN ('ACTIVO', 'PASIVO', 'PATRIMONIO', 'INGRESO', 'GASTO'))
);

ALTER TABLE CUENTA ADD CONSTRAINT UQ_CUENTA_CODIGO UNIQUE (CODIGO);

CREATE SEQUENCE SEQ_USUARIO_APLICACION START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE TABLE USUARIO_APLICACION (
  ID_USUARIO NUMBER PRIMARY KEY,
  NOMBRE_USUARIO VARCHAR2(100 CHAR) NOT NULL,
  PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
  ROL VARCHAR2(20 CHAR) NOT NULL,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT UQ_USUARIO_APLICACION_NOMBRE UNIQUE (NOMBRE_USUARIO),
  CONSTRAINT CK_USUARIO_APLICACION_ROL CHECK (ROL IN ('ADMINISTRADOR', 'USUARIO')),
  CONSTRAINT CK_USUARIO_APLICACION_ACTIVO CHECK (ACTIVO IN (0, 1))
);

PROMPT Migracion aplicada. Revise NATURALEZA y CLASIFICACION de los tipos existentes antes de generar reportes.
